// Generates the backend seed migrations from the frontend data (src/data), so both stay in sync:
//   V2__seed_destinations.sql  English base content (src/data/<slug>.ts)
//   R__seed_translations.sql   translated content    (src/data/<lang>/<slug>.ts)
// Usage: npm run seed:sql
//
// V2 is a versioned migration: once a database has applied it, Flyway refuses to start if the
// file changes. Change English content on a live database through the admin API instead.
// R__ is repeatable: Flyway re-runs it whenever its content changes, so translations can be
// edited and regenerated at any time.
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const tmp = resolve(root, 'node_modules/.cache/seed-data.mjs');
const migrations = resolve(root, '../backend/src/main/resources/db/migration');
const seedFile = resolve(migrations, 'V2__seed_destinations.sql');
const translationsFile = resolve(migrations, 'R__seed_translations.sql');

await build({
  stdin: {
    contents:
      "export { DESTINATIONS } from './src/data/index.ts';\n" +
      "export { CONTENT_LANGS, loadContentTranslations } from './src/data/translations.ts';\n",
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true, format: 'esm', platform: 'node', outfile: tmp, logLevel: 'error',
});
const { DESTINATIONS, CONTENT_LANGS, loadContentTranslations } = await import(`${pathToFileURL(tmp).href}?t=${Date.now()}`);
// Same loaders the site uses (src/data/translations.ts); esbuild inlines their dynamic imports.
const TRANSLATIONS = Object.fromEntries(
  await Promise.all(CONTENT_LANGS.map(async (lang) => [lang, await loadContentTranslations(lang)])),
);

const q = (v) => (v === undefined || v === null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const destId = (d) => `(SELECT id FROM destination WHERE slug = ${q(d.slug)})`;
const placeId = (d, p) =>
  `(SELECT p.id FROM place p JOIN destination d ON d.id = p.destination_id WHERE d.slug = ${q(d.slug)} AND p.slug = ${q(p.slug)})`;

// ---- V2: English base content ----------------------------------------------------------

const lines = ['-- GENERATED by frontend/scripts/generate-seed-sql.mjs - do not edit by hand.', ''];

DESTINATIONS.forEach((d, di) => {
  lines.push(`-- ${d.name}`);
  lines.push(
    'INSERT INTO destination (slug, name, flag, region, vibes, tagline, description, best_time_to_visit, hero_image_url, lat, lng, sort_order) VALUES ' +
      `(${q(d.slug)}, ${q(d.name)}, ${q(d.flag)}, ${q(d.region)}, ${q(d.vibes.join(','))}, ${q(d.tagline)}, ${q(d.description)}, ` +
      `${q(d.bestTimeToVisit)}, ${q(d.heroImageUrl)}, ${d.lat}, ${d.lng}, ${di});`,
  );
  d.places.forEach((p, pi) => {
    lines.push(
      'INSERT INTO place (destination_id, slug, name, description, fun_fact, hero_image_url, sort_order) VALUES ' +
        `(${destId(d)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${q(p.funFact)}, ${q(p.heroImageUrl)}, ${pi});`,
    );
    p.activities.forEach((a) => {
      lines.push(
        'INSERT INTO activity (place_id, rank_no, title, description, image_url) VALUES ' +
          `(${placeId(d, p)}, ${a.rank}, ${q(a.title)}, ${q(a.description)}, ${q(a.imageUrl)});`,
      );
    });
    p.gallery.forEach((g, gi) => {
      lines.push(
        'INSERT INTO image (place_id, url, caption, sort_order) VALUES ' +
          `(${placeId(d, p)}, ${q(g.url)}, ${q(g.caption)}, ${gi});`,
      );
    });
  });
  lines.push('');
});

// ---- R__: translations -----------------------------------------------------------------

// Column sizes from V4__content_translations.sql; TEXT columns have no limit.
const MAX = { name: 200, tagline: 500, bestTimeToVisit: 500, title: 300, caption: 500 };
const problems = [];
const checkLen = (where, field, v) => {
  if (MAX[field] && typeof v === 'string' && v.length > MAX[field]) {
    problems.push(`${where}: ${field} is ${v.length} characters (max ${MAX[field]})`);
  }
};
const hasText = (...vs) => vs.some((v) => typeof v === 'string' && v.trim() !== '');

const tr = [
  '-- GENERATED by frontend/scripts/generate-seed-sql.mjs from src/data/<lang>/ - do not edit by hand.',
  '-- Repeatable migration: Flyway re-runs it whenever this file changes. It replaces all translations,',
  '-- matching the English rows by slug, rank and gallery position. INSERT ... SELECT skips rows whose',
  '-- English content no longer exists (for example a destination deleted through the admin API).',
  '',
  'DELETE FROM image_translation;',
  'DELETE FROM activity_translation;',
  'DELETE FROM place_translation;',
  'DELETE FROM destination_translation;',
  '',
];
let rowCount = 0;

for (const [lang, byDest] of Object.entries(TRANSLATIONS)) {
  for (const [slug, t] of Object.entries(byDest)) {
    const d = DESTINATIONS.find((x) => x.slug === slug);
    if (!d) {
      problems.push(`${lang}/${slug}: no destination with slug "${slug}"`);
      continue;
    }
    const L = q(lang);
    const D = q(slug);
    tr.push(`-- ${d.name} (${lang})`);

    for (const f of ['name', 'tagline', 'bestTimeToVisit']) checkLen(`${lang}/${slug}`, f, t[f]);
    if (hasText(t.name, t.tagline, t.description, t.bestTimeToVisit)) {
      tr.push(
        'INSERT INTO destination_translation (destination_id, lang, name, tagline, description, best_time_to_visit) ' +
          `SELECT id, ${L}, ${q(t.name)}, ${q(t.tagline)}, ${q(t.description)}, ${q(t.bestTimeToVisit)} ` +
          `FROM destination WHERE slug = ${D};`,
      );
      rowCount++;
    }

    for (const [pSlug, pt] of Object.entries(t.places ?? {})) {
      const p = d.places.find((x) => x.slug === pSlug);
      const where = `${lang}/${slug}/${pSlug}`;
      if (!p) {
        problems.push(`${where}: no place with slug "${pSlug}" in ${slug}`);
        continue;
      }
      const P = q(pSlug);
      const placeJoin = `JOIN place p ON p.id = x.place_id JOIN destination d ON d.id = p.destination_id ` +
        `WHERE d.slug = ${D} AND p.slug = ${P}`;

      checkLen(where, 'name', pt.name);
      if (hasText(pt.name, pt.description, pt.funFact)) {
        tr.push(
          'INSERT INTO place_translation (place_id, lang, name, description, fun_fact) ' +
            `SELECT p.id, ${L}, ${q(pt.name)}, ${q(pt.description)}, ${q(pt.funFact)} ` +
            `FROM place p JOIN destination d ON d.id = p.destination_id WHERE d.slug = ${D} AND p.slug = ${P};`,
        );
        rowCount++;
      }

      for (const [rankKey, at] of Object.entries(pt.activities ?? {})) {
        const rank = Number(rankKey);
        if (!p.activities.some((a) => a.rank === rank)) {
          problems.push(`${where}: no activity with rank ${rankKey}`);
          continue;
        }
        checkLen(`${where}#${rank}`, 'title', at?.title);
        if (at && hasText(at.title, at.description)) {
          tr.push(
            'INSERT INTO activity_translation (activity_id, lang, title, description) ' +
              `SELECT x.id, ${L}, ${q(at.title)}, ${q(at.description)} FROM activity x ${placeJoin} AND x.rank_no = ${rank};`,
          );
          rowCount++;
        }
      }

      const captions = pt.gallery ?? [];
      if (captions.length > p.gallery.length) {
        problems.push(`${where}: ${captions.length} gallery captions, but the English gallery has ${p.gallery.length} images`);
      }
      captions.slice(0, p.gallery.length).forEach((c, i) => {
        checkLen(`${where} gallery[${i}]`, 'caption', c);
        if (hasText(c)) {
          tr.push(
            'INSERT INTO image_translation (image_id, lang, caption) ' +
              `SELECT x.id, ${L}, ${q(c)} FROM image x ${placeJoin} AND x.sort_order = ${i};`,
          );
          rowCount++;
        }
      });
    }
    tr.push('');
  }
}

// Nothing is written while the translations do not match the English data.
if (problems.length) {
  console.error('Translation problems (nothing was written):\n  - ' + problems.join('\n  - '));
  process.exit(1);
}

mkdirSync(migrations, { recursive: true });
writeFileSync(seedFile, lines.join('\n'));
writeFileSync(translationsFile, tr.join('\n'));
console.log(`Wrote ${seedFile} (${DESTINATIONS.length} destinations)`);
const translated = Object.entries(TRANSLATIONS).map(([l, m]) => `${l}: ${Object.keys(m).join(', ') || 'none'}`).join('; ');
console.log(`Wrote ${translationsFile} (${rowCount} rows; ${translated})`);
